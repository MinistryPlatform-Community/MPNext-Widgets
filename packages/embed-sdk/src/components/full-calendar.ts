/**
 * The four pinned FullCalendar 7 assets, each with its Subresource Integrity
 * hash. Two scripts (core, then theme — order matters, the theme IIFE consumes
 * `FullCalendar.Shared`) and two stylesheets.
 *
 * BUMPING FC_VERSION OR FC_THEME REQUIRES RECOMPUTING EVERY HASH HERE. A stale
 * hash makes the browser refuse the asset with no visible error of its own: a
 * bad script hash surfaces as "Failed to load calendar library." on week/grid,
 * and a bad stylesheet hash silently renders an unstyled calendar. Recompute
 * all four in the same edit as the bump:
 *
 *   for f in all/global.js themes/<theme>/global.js \
 *            skeleton.css themes/<theme>/theme.css; do
 *     printf '%-28s sha384-%s\n' "$f" \
 *       "$(curl -sL "https://cdn.jsdelivr.net/npm/fullcalendar@<ver>/$f" \
 *          | openssl dgst -sha384 -binary | openssl base64 -A)"
 *   done
 *
 * Use `all/global.js`, never `all/global.min.js`: v7 publishes no minified
 * global bundle, and jsDelivr's `.min.js` is generated on the fly, so a hash
 * over it would pin CDN-generated bytes rather than author-published ones (the
 * trap that `add-to-calendar-button` fell into — .claude/TODO/15). All four
 * URLs above were verified byte-identical to the npm tarball's own copies.
 *
 * NOTE: `themes/<theme>/palette.css` is deliberately NOT loaded. It defines
 * every theme custom property on `:root`, which never matches inside a shadow
 * tree, while `theme.css` consumes them in 67 of 68 `var()` uses with no
 * fallback — so shipping it yields a calendar with no borders, no today
 * highlight, no event chips and no now-indicator. `FC7_THEME_VARS` in
 * full-calendar-styles.ts supplies the whole contract on `:host` instead, in
 * brand colours.
 */
